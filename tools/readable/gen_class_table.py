#!/usr/bin/env python3
"""build/gen/class_table.h for the runtime's debug tools: each named class's vtable, name and confidence, from classes.toml and the
vtables named in types.toml. Names only, as those files already hold: no game data. gen_class_table.py OUT"""
import os
import sys
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))


def main(out):
    with open(os.path.join(HERE, "classes.toml"), "rb") as f:
        classes = tomllib.load(f).get("class", [])
    with open(os.path.join(HERE, "types.toml"), "rb") as f:
        structs = tomllib.load(f).get("struct", [])
    table = {int(c["vtable"], 16): (c["name"], c.get("confidence", "guess")) for c in classes}
    for s in structs:
        for vt in s.get("vtables", []):
            # (the classes.toml entry's confidence if it has one; a vtable named only in types.toml is the struct's: the hunter's)
            table.setdefault(int(vt, 16), (s["name"], s.get("confidence", "inferred")))
    rows = sorted(table.items())
    tmp = out + ".tmp"
    with open(tmp, "w") as f:
        f.write("/* Generated by tools/readable/gen_class_table.py */\n")
        for vt, (name, conf) in rows:
            f.write(f'{{0x{vt:08X}u, "{name}", "{conf}"}},\n')
    os.replace(tmp, out)


if __name__ == "__main__":
    main(sys.argv[1])
