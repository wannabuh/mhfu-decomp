#!/usr/bin/env python3
"""From tools/readable/types.toml and names/*.toml: gen_types.py WORK [HEADER]. Writes WORK/view-names.tsv and WORK/view-types.tsv
for the view (DecompileModule.java) and the C header, whose offsets are checked at compile time. A vtable's methods get their
struct as `this`, from WORK/methods.json."""
import glob
import json
import os
import sys
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
SIZE = {"u8": 1, "s8": 1, "u16": 2, "s16": 2, "u32": 4, "s32": 4, "f32": 4, "ptr": 4, "f32x3": 12, "f32x4": 16}
CTYPE = {"u8": "uint8_t", "s8": "int8_t", "u16": "uint16_t", "s16": "int16_t", "u32": "uint32_t", "s32": "int32_t",
         "f32": "float", "ptr": "uint32_t"}


def size_of(t):
    return 4 if t.startswith("ptr:") else SIZE[t]


def field_decl(f):
    t = f["type"]
    if t in ("f32x3", "f32x4"):
        return f"float {f['name']}[{t[-1]}];"
    return f"{CTYPE['ptr' if t.startswith('ptr:') else t]} {f['name']};"


def main():
    work = sys.argv[1]
    header = sys.argv[2] if len(sys.argv) > 2 else None
    owners = {}
    with open(os.path.join(work, "allfuncs.tsv")) as f:
        for line in f:
            a, m = line.rstrip("\n").split("\t")
            owners.setdefault(int(a, 16), []).append(m)
    seen = {}
    for path in sorted(glob.glob(os.path.join(HERE, "names", "*.toml"))):
        with open(path, "rb") as f:
            for e in tomllib.load(f).get("function", []):
                key = (e["module"], int(e["address"], 16))
                # known.toml sorts after nothing else by rule: a confirmed entry is never replaced by a weaker one
                rank = {"confirmed": 2, "inferred": 1, "guess": 0}[e["confidence"]]
                if key not in seen or rank > seen[key][0] or os.path.basename(path) == "known.toml":
                    seen[key] = (rank, e)
    with open(os.path.join(work, "view-names.tsv"), "w") as f:
        for (m, a), (_r, e) in sorted(seen.items()):
            purpose = " ".join(e.get("purpose", "").split())
            f.write(f"{m}\t{a:x}\t{e['name']}\t{e['confidence']}\t{purpose}\n")
    with open(os.path.join(HERE, "types.toml"), "rb") as f:
        types = tomllib.load(f)
    methods = {}
    if os.path.exists(os.path.join(work, "methods.json")):      # (tools/readable/vtables.py)
        with open(os.path.join(work, "methods.json")) as f:
            methods = json.load(f)
    lines = ["/* Generated by tools/readable/gen_types.py from types.toml: the game's structures, offsets checked. */",
             "#pragma once", "#include <stddef.h>", "#include <stdint.h>", ""]
    with open(os.path.join(work, "view-types.tsv"), "w") as out:
        for s in types.get("struct", []):
            fields = sorted(s["fields"], key=lambda x: x["offset"])
            out.write(f"S\t{s['name']}\t{s['span']:x}\n")
            lines.append(f"typedef struct {s['name']} {{")
            at, pad = 0, 0
            for fd in fields:
                if fd["offset"] < at:
                    raise SystemExit(f"{s['name']}.{fd['name']}: overlaps the field before it")
                if fd["offset"] > at:
                    lines.append(f"    uint8_t pad{pad}[0x{fd['offset'] - at:X}];")
                    pad += 1
                note = fd.get("note")
                conf = fd.get("confidence", "guess")
                lines.append(f"    {field_decl(fd)}  /* +0x{fd['offset']:X} {conf}{': ' + note if note else ''} */")
                at = fd["offset"] + size_of(fd["type"])
                out.write(f"F\t{s['name']}\t{fd['offset']:x}\t{fd['type']}\t{fd['name']}\n")
            if at > s["span"]:
                raise SystemExit(f"{s['name']}: its fields go past its span")
            if s["span"] > at:
                lines.append(f"    uint8_t pad{pad}[0x{s['span'] - at:X}];")
            lines.append(f"}} {s['name']};")
            for fd in fields:
                lines.append(f"_Static_assert(offsetof({s['name']}, {fd['name']}) == 0x{fd['offset']:X}, \"{fd['name']}\");")
            if "size" in s:
                lines.append(f"_Static_assert(sizeof({s['name']}) == 0x{s['size']:X}, \"size\");")
            lines.append("")
            for m, a in s.get("functions", []):
                out.write(f"P\t{m}\t{int(a, 16):x}\t0\t{s['name']}\n")
            # A vtable's methods: this struct as `this`, or Object where other classes share the method
            own = {f"{int(v, 16):08X}" for v in s.get("vtables", [])}
            for key, slots in methods.items():
                vts = {v for v, _o in slots}
                if vts & own:
                    m, a = key.split()
                    out.write(f"P\t{m}\t{a}\t0\t{s['name'] if vts <= own else 'Object'}\n")
    if header:
        with open(header, "w") as f:
            f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
