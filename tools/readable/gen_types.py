#!/usr/bin/env python3
"""From tools/readable/types.toml and names/*.toml: gen_types.py WORK [HEADER]. Writes WORK/view-names.tsv and WORK/view-types.tsv
for the view (DecompileModule.java), with every class classes.py found, and the C header of types.toml's named fields, whose
offsets are checked at compile time."""
import collections
import glob
import json
import os
import sys
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
SPAN = 0x2000     # past a struct's span the decompiler prints self[1].field_X, which reads wrongly: kept generous
SIZE = {"u8": 1, "s8": 1, "u16": 2, "s16": 2, "u32": 4, "s32": 4, "f32": 4, "ptr": 4, "f32x3": 12, "f32x4": 16}
CTYPE = {"u8": "uint8_t", "s8": "int8_t", "u16": "uint16_t", "s16": "int16_t", "u32": "uint32_t", "s32": "int32_t",
         "f32": "float", "ptr": "uint32_t"}


def size_of(t):
    return 4 if t.startswith("ptr:") else SIZE[t]


def field_decl(f):
    t = f["type"]
    if t in ("f32x3", "f32x4"):
        return f"float {f['name']}[{t[-1]}];"
    return f"{CTYPE['ptr' if t.startswith('ptr:') else t]} {f['name']};"


def main():
    work = sys.argv[1]
    header = sys.argv[2] if len(sys.argv) > 2 else None
    owners = {}
    with open(os.path.join(work, "allfuncs.tsv")) as f:
        for line in f:
            a, m = line.rstrip("\n").split("\t")
            owners.setdefault(int(a, 16), []).append(m)
    seen = {}
    for path in sorted(glob.glob(os.path.join(HERE, "names", "*.toml"))):
        with open(path, "rb") as f:
            for e in tomllib.load(f).get("function", []):
                key = (e["module"], int(e["address"], 16))
                # known.toml sorts after nothing else by rule: a confirmed entry is never replaced by a weaker one
                rank = {"confirmed": 2, "inferred": 1, "guess": 0}[e["confidence"]]
                if key not in seen or rank > seen[key][0] or os.path.basename(path) == "known.toml":
                    seen[key] = (rank, e)
    # A name says one function: where several have the same one, each takes its address (names/ keeps the shared name)
    counts = collections.Counter(e["name"] for _r, e in seen.values())
    with open(os.path.join(work, "view-names.tsv"), "w") as f:
        for (m, a), (_r, e) in sorted(seen.items()):
            purpose = " ".join(e.get("purpose", "").split())
            name = e["name"] if counts[e["name"]] == 1 else f"{e['name']}_{a:08X}"
            f.write(f"{m}\t{a:x}\t{name}\t{e['confidence']}\t{purpose}\n")
    with open(os.path.join(HERE, "types.toml"), "rb") as f:
        types = tomllib.load(f)
    named = {s["name"]: s for s in types.get("struct", [])}
    write_view_types(work, types)
    if header:
        write_header(header, named)


def inherited(s, named):
    """A struct's fields, its bases' first: a name further down the tree wins at the same offset."""
    chain = [s]
    while "base" in chain[-1]:
        chain.append(named[chain[-1]["base"]])
    at = {}
    for c in reversed(chain):
        for fd in c.get("fields", []):
            at[fd["offset"]] = fd
    return [at[o] for o in sorted(at)]


def write_header(path, named):
    lines = ["/* Generated by tools/readable/gen_types.py from types.toml: the game's structures, offsets checked. */",
             "#pragma once", "#include <stddef.h>", "#include <stdint.h>", ""]
    for s in named.values():
        fields = inherited(s, named)
        if not fields:
            continue
        lines.append(f"typedef struct {s['name']} {{")
        at, pad = 0, 0
        for fd in fields:
            if fd["offset"] < at:
                raise SystemExit(f"{s['name']}.{fd['name']}: overlaps the field before it")
            if fd["offset"] > at:
                lines.append(f"    uint8_t pad{pad}[0x{fd['offset'] - at:X}];")
                pad += 1
            note = fd.get("note")
            lines.append(f"    {field_decl(fd)}  /* +0x{fd['offset']:X} {fd.get('confidence', 'guess')}{': ' + note if note else ''} */")
            at = fd["offset"] + size_of(fd["type"])
        span = s.get("span", SPAN)
        if at > span:
            raise SystemExit(f"{s['name']}: its fields go past its span")
        lines.append(f"    uint8_t pad{pad}[0x{span - at:X}];")
        lines.append(f"}} {s['name']};")
        for fd in fields:
            lines.append(f"_Static_assert(offsetof({s['name']}, {fd['name']}) == 0x{fd['offset']:X}, \"{fd['name']}\");")
        if "size" in s:
            lines.append(f"_Static_assert(sizeof({s['name']}) == 0x{s['size']:X}, \"size\");")
        lines.append("")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def auto_type(access, pointer, deref, names):
    """A field's type from how the code reaches it: the width it is mostly used at; float if ever loaded as one."""
    if pointer:
        return f"ptr:{names[pointer]}"
    width = collections.Counter()
    for kind, w, _write, n in access:
        if kind != "vec":
            width[w] += n
    if not width:
        return None         # only as a whole vector: part of an array whose elements have no use of their own
    w = width.most_common(1)[0][0]
    kinds = collections.Counter()
    for kind, kw, _write, n in access:
        if kw == w:
            kinds[kind] += n
    if w == 4:
        return "f32" if kinds["f32"] else "ptr" if deref else "s32"
    loads = [(n, k) for k, n in kinds.items() if k[0] in "su"]
    if loads:
        return max(loads)[1]
    return "u8" if w == 1 else "u16"


def write_view_types(work, types):
    """All the game's classes for the view, flat: names from types.toml, the rest field_<offset>, typed by classes.py's evidence."""
    named_by_vt = {}
    for s in types.get("struct", []):
        for v in s.get("vtables", []):
            named_by_vt[v.upper()] = s
    named = {s["name"]: s for s in types.get("struct", [])}
    path = os.path.join(work, "classes.json")
    with open(os.path.join(work, "view-types.tsv"), "w") as out:
        if not os.path.exists(path):
            return
        with open(path) as f:
            data = json.load(f)
        classes = data["classes"]
        names = {v: named_by_vt[v]["name"] if v in named_by_vt else f"Class_{v}" for v in classes}
        rows = []
        for v, c in classes.items():
            chain = [v]
            while classes[chain[-1]]["parent"] and classes[chain[-1]]["parent"] not in chain:
                chain.append(classes[chain[-1]]["parent"])
            merged = {}
            for a in chain:
                for off, fd in classes[a]["fields"].items():
                    m = merged.setdefault(int(off, 16), {"access": [], "pointer": None, "deref": False})
                    m["access"] += fd["access"]
                    m["pointer"] = m["pointer"] or fd["pointer"]
                    m["deref"] = m["deref"] or fd["deref"]
                for off, p in classes[a]["pointer_only"].items():
                    m = merged.setdefault(int(off, 16), {"access": [], "pointer": None, "deref": False})
                    m["pointer"] = m["pointer"] or p
            span = max(SPAN, c["extent"] + 0x100)
            out.write(f"S\t{names[v]}\t{span:x}\n")
            placed = []     # (offset, end)
            s = next((named_by_vt[a] for a in chain if a in named_by_vt), None)
            for fd in inherited(s, named) if s else []:
                placed.append((fd["offset"], fd["offset"] + size_of(fd["type"])))
                rows.append(f"F\t{names[v]}\t{fd['offset']:x}\t{fd['type']}\t{fd['name']}\n")
            for off, m in sorted(merged.items(), key=lambda kv: -sum(a[3] for a in kv[1]["access"])):
                t = auto_type(m["access"], m["pointer"] and names[m["pointer"]] and m["pointer"], m["deref"], names)
                if not t:
                    continue
                end = off + size_of(t)
                if off == 0 or any(off < e and b < end for b, e in placed):
                    continue
                placed.append((off, end))
                rows.append(f"F\t{names[v]}\t{off:x}\t{t}\tfield_{off:X}\n")
        out.write("".join(rows))
        for key, (v, _how) in data["this"].items():
            m, a = key.split()
            out.write(f"P\t{m}\t{a}\ta0\t{names[v]}\n")
        for key, v in data["args"].items():
            m, a, reg = key.split()
            out.write(f"P\t{m}\t{a}\ta{int(reg) - 4}\t{names[v]}\n")
        for a, v in data["globals"].items():
            out.write(f"G\t{a}\t{names[v]}\n")


if __name__ == "__main__":
    main()
